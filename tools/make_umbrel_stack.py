"""Write umbrel/compose.yaml: one self-contained stack for Dockge on Umbrel.

Data: Dockge's inner Docker daemon has /External/btcdata/alibi-data (the 2 TB
external drive, not the system SSD) mounted at /mnt/alibi-data via an Umbrel custom
mount on the dockge "docker" service. Bind-mounting that path survives Dockge
restarts; other bind mounts would not.

Code: nothing on the box can see this project folder, so the recorder source
travels inside the compose file itself (compose
`configs` with inline content) and the image is built from an inline Dockerfile.
Re-run after any code change, then paste the result into Dockge.

    python tools/make_umbrel_stack.py
"""

from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "alibi_recorder"
OUT = ROOT / "umbrel" / "compose.yaml"

# The external drive also carries the Bitcoin node's chain: stop well before it fills.
ENV = {
    "ALIBI_DATA_DIR": "/data/ais",
    "ALIBI_DISK_WARN_GB": "20",
    "ALIBI_DISK_STOP_GB": "10",
}


def block(text: str, indent: int) -> str:
    pad = " " * indent
    text = text.replace("$", "$$")  # compose interpolation
    return "\n".join(pad + line if line else "" for line in text.splitlines())


def main() -> None:
    files = sorted(SRC.glob("*.py"))
    requirements = (ROOT / "requirements.txt").read_text(encoding="utf-8").split()
    out = [
        "# GENERATED by tools/make_umbrel_stack.py - do not edit, regenerate.",
        "name: alibi",
        "services:",
        "  recorder:",
        "    image: alibi-recorder:0.1",
        "    build:",
        "      context: .",
        "      dockerfile_inline: |",
        "        FROM python:3.12-slim",
        "        ENV PYTHONUNBUFFERED=1",
        f"        RUN pip install --no-cache-dir {' '.join(requirements)}",
        "        WORKDIR /app",
        '        CMD ["python", "-m", "alibi_recorder"]',
        "    container_name: alibi-recorder",
        "    restart: unless-stopped",
        "    stop_grace_period: 30s",
        "    environment:",
        *[f"      {k}: \"{v}\"" for k, v in ENV.items()],
        "    volumes:",
        "      - /mnt/alibi-data:/data",
        "    configs:",
        *[f"      - source: {f.stem.strip('_') or 'pkg'}\n        target: /app/alibi_recorder/{f.name}" for f in files],
        "    logging:",
        "      driver: json-file",
        "      options:",
        '        max-size: "20m"',
        '        max-file: "5"',
        # Context recorder: same image and code, its own process, so neither can stop the other.
        # Builds the same image itself (cached, so free): never depends on pulling a local-only tag.
        "  context:",
        "    image: alibi-recorder:0.1",
        "    build:",
        "      context: .",
        "      dockerfile_inline: |",
        "        FROM python:3.12-slim",
        "        ENV PYTHONUNBUFFERED=1",
        f"        RUN pip install --no-cache-dir {' '.join(requirements)}",
        "        WORKDIR /app",
        '        CMD ["python", "-m", "alibi_recorder"]',
        '    command: ["python", "-m", "alibi_recorder", "context"]',
        "    container_name: alibi-context",
        "    restart: unless-stopped",
        "    stop_grace_period: 30s",
        "    environment:",
        '      ALIBI_CONTEXT_DIR: "/data/context"',
        "    volumes:",
        "      - /mnt/alibi-data:/data",
        "    configs:",
        *[f"      - source: {f.stem.strip('_') or 'pkg'}\n        target: /app/alibi_recorder/{f.name}" for f in files],
        "    logging:",
        "      driver: json-file",
        "      options:",
        '        max-size: "10m"',
        '        max-file: "3"',
        "configs:",
    ]
    for f in files:
        out.append(f"  {f.stem.strip('_') or 'pkg'}:")
        out.append("    content: |")
        out.append(block(f.read_text(encoding="utf-8"), 6))
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {OUT} ({OUT.stat().st_size / 1e3:.0f} kB, {len(files)} source files)")


if __name__ == "__main__":
    main()
